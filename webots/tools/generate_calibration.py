"""Generate static calibration worlds for the e-puck proximity sensors.

Why this exists
---------------
The avoidance logic compares side sensor readings against a fixed threshold
(``side_block = 200``), but those readings are raw intensities, not distances.
In the archived runs the threshold was never reached, so the "compare left and
right space" idea never actually fired — the controller fell back to "prefer the
target side" and got lucky.

Measured sensor orientation (from the official E-puck.proto, verified against
archived runs) — this table did not exist in the project before:

    ps0  -17.2 deg      ps7  +17.1 deg     (front pair)
    ps1  -45.9 deg      ps6  +45.8 deg     (front-diagonal pair)
    ps2  -90.0 deg      ps5  +90.0 deg     (lateral pair)
    ps3 -151.5 deg      ps4 +151.2 deg     (rear pair)

Angles are counter-clockwise from +X, and e-puck's +Y points to its left.

Design: everything is static
----------------------------
An earlier version had a Supervisor teleport the obstacle between samples. That
turned into five stacked failures (controller never started, logging swallowed,
``customData`` absent on Solid, sampling window mismatched, and finally the box
not actually colliding where it was moved). Each fix exposed the next.

This generator avoids the whole class of problems: one world per (bearing,
distance), with both the robot pose and the obstacle pose written literally into
the file. Nothing moves during a run, so there is nothing to synchronise and
nothing that can silently fail to update.

The cost is a larger number of small world files. That is a good trade — the
files are generated, not authored.

Usage
-----
    python tools/generate_calibration.py            # write all worlds
    python tools/generate_calibration.py --list     # show the plan only
    python tools/generate_calibration.py --bearing -90 --dist 0.08   # one world

No external dependencies.
"""

from __future__ import annotations

import argparse
import json
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
WORLD_DIR = ROOT / "worlds"
SIDECAR_DIR = ROOT / "logs" / "worlds"

# The obstacle sits on the +X axis at a fixed distance; the robot is placed on a
# ring around it. Rotating the robot as well would change which sensors see the
# box, so the robot heading is held at 0 and only the offset changes.
OBSTACLE_POS = (0.0, 0.0)
OBSTACLE_SIZE = 0.10

BEARINGS = [-90.0, -45.0, 0.0, 45.0, 90.0]
DISTANCES = [0.03, 0.04, 0.05, 0.06, 0.08, 0.10, 0.13, 0.16, 0.20, 0.25, 0.30, 0.40]

# A generous arena: the robot can be 0.40 m from the obstacle on any bearing, and
# the wall must stay far enough away that it never enters the sensor cone.
ARENA_SIZE = 2.0

HEADER = '''#VRML_SIM R2025a utf8
# Calibration world generated by tools/generate_calibration.py — do not edit.
# Static layout: the robot pose and the obstacle pose are both literal values,
# nothing moves during the run. Bearing={bearing:.1f} deg, face distance={distance:.3f} m

EXTERNPROTO "https://raw.githubusercontent.com/cyberbotics/webots/R2025a/projects/objects/backgrounds/protos/TexturedBackground.proto"
EXTERNPROTO "https://raw.githubusercontent.com/cyberbotics/webots/R2025a/projects/objects/backgrounds/protos/TexturedBackgroundLight.proto"
EXTERNPROTO "https://raw.githubusercontent.com/cyberbotics/webots/R2025a/projects/objects/floors/protos/RectangleArena.proto"
EXTERNPROTO "https://raw.githubusercontent.com/cyberbotics/webots/R2025a/projects/robots/gctronic/e-puck/protos/E-puck.proto"

WorldInfo {{
  basicTimeStep 32
  info [
    "e-puck proximity sensor calibration"
  ]
  title "e-puck sensor calibration"
}}
Viewpoint {{
  orientation -0.577 0.577 0.577 2.094
  position 1.4 1.4 1.4
}}

TexturedBackground {{
}}

TexturedBackgroundLight {{
}}

RectangleArena {{
  floorSize {arena:.1f} {arena:.1f}
}}

DEF E_PUCK E-puck {{
  translation {rx:.4f} {ry:.4f} 0
  rotation 0 0 1 0
  controller "calibration_controller"
}}

DEF CALIBRATION_OBSTACLE Solid {{
  translation {ox:.4f} {oy:.4f} {oz:.4f}
  children [
    Shape {{
      appearance PBRAppearance {{
        baseColor 0.80 0.20 0.20
        roughness 0.5
        metalness 0
      }}
      geometry Box {{
        size {size:.3f} {size:.3f} {size:.3f}
      }}
    }}
  ]
  name "calibration obstacle"
  boundingObject Box {{
    size {size:.3f} {size:.3f} {size:.3f}
  }}
}}
'''


def robot_position(bearing_deg: float, face_distance: float) -> tuple[float, float]:
    """Robot centre placed so that the obstacle sits at ``bearing_deg`` as seen
    FROM THE ROBOT.

    The robot always keeps heading 0 (its +X is world +X). To make the obstacle
    appear at bearing b in the robot frame, the robot must sit at -b from the box:

        box at bearing +90 (robot's left)  -> robot is placed at -90 from the box
        box at bearing 180 (behind robot)  -> robot is placed at 0 from the box,
                                              i.e. on the box's +X side

    An earlier version placed the robot AT the bearing, which silently mirrored
    every measurement: bearing 180 produced front-sensor hits because the box
    really was in front. Verified against runs at bearings 0/90/180.
    """

    reach = face_distance + OBSTACLE_SIZE / 2.0
    theta = math.radians(bearing_deg + 180.0)
    return (
        OBSTACLE_POS[0] + reach * math.cos(theta),
        OBSTACLE_POS[1] + reach * math.sin(theta),
    )


def world_name(bearing_deg: float, face_distance: float) -> str:
    """Stable file name; the sign is explicit so -45 and 45 never collide."""

    sign = "p" if bearing_deg >= 0 else "m"
    return f"calib_b{sign}{abs(bearing_deg):03.0f}_d{int(round(face_distance * 1000)):03d}"


def build_world(bearing_deg: float, face_distance: float) -> str:
    rx, ry = robot_position(bearing_deg, face_distance)
    ox, oy = OBSTACLE_POS
    return HEADER.format(
        bearing=bearing_deg,
        distance=face_distance,
        arena=ARENA_SIZE,
        rx=rx,
        ry=ry,
        ox=ox,
        oy=oy,
        oz=OBSTACLE_SIZE / 2.0,
        size=OBSTACLE_SIZE,
    )


def plan() -> list[tuple[float, float]]:
    return [(b, d) for b in BEARINGS for d in DISTANCES]


def write_one(bearing_deg: float, face_distance: float) -> Path:
    name = world_name(bearing_deg, face_distance)
    world_path = WORLD_DIR / f"{name}.wbt"
    world_path.write_text(build_world(bearing_deg, face_distance), encoding="utf-8", newline="\n")

    rx, ry = robot_position(bearing_deg, face_distance)
    sidecar = {
        "scenario": "calibration",
        "seed": name,
        "world": f"{name}.wbt",
        "arena_size_m": ARENA_SIZE,
        "start": [rx, ry],
        "target": [rx, ry],  # unused; the robot never moves
        "path_found": True,
        "calibration": {
            "bearing_deg": bearing_deg,
            "face_distance_m": face_distance,
            "obstacle_size_m": OBSTACLE_SIZE,
            "robot_pose": [rx, ry, 0.0],
        },
        "obstacles": [
            {
                "name": "CALIBRATION_OBSTACLE",
                "x": OBSTACLE_POS[0],
                "y": OBSTACLE_POS[1],
                "size": OBSTACLE_SIZE,
            }
        ],
    }
    (SIDECAR_DIR / f"{name}.json").write_text(
        json.dumps(sidecar, indent=2, ensure_ascii=False) + "\n",
        encoding="utf-8",
        newline="\n",
    )
    return world_path


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--list", action="store_true", help="print the plan, write nothing")
    parser.add_argument("--bearing", type=float, help="generate a single bearing")
    parser.add_argument("--dist", type=float, help="generate a single distance")
    args = parser.parse_args()

    pairs = plan()

    if args.list:
        print(f"{len(pairs)} worlds")
        for bearing, distance in pairs:
            print(f"  {world_name(bearing, distance)}  bearing={bearing:+.0f} dist={distance:.3f}")
        return 0

    WORLD_DIR.mkdir(parents=True, exist_ok=True)
    SIDECAR_DIR.mkdir(parents=True, exist_ok=True)

    if args.bearing is not None and args.dist is not None:
        path = write_one(args.bearing, args.dist)
        print(f"wrote {path.name}")
        return 0

    written = 0
    for bearing, distance in pairs:
        write_one(bearing, distance)
        written += 1

    print(f"CALIBRATION_WORLDS={written}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
